import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const read = (path) => readFile(new URL(path, import.meta.url), 'utf8');
const pkg = JSON.parse(await read('../package.json'));
const lock = JSON.parse(await read('../package-lock.json'));
const adapter = await read('../src/platform/scanner/decoders/zxingWasmDecoder.ts');
const candidateFactory = await read('../src/platform/scanner/decoders/zxingWasmDecoderFactory.ts');
const defaultFactory = await read('../src/platform/scanner/decoders/decoderFactory.ts');
const session = await read('../src/platform/scanner/universalScannerSession.ts');
assert.equal(pkg.dependencies['zxing-wasm'], '3.1.6');
assert.equal(lock.packages[''].dependencies['zxing-wasm'], '3.1.6');
assert.equal(lock.packages['node_modules/zxing-wasm'].version, '3.1.6');
assert.match(adapter, /from 'zxing-wasm\/reader'/);
assert.match(adapter, /zxing-wasm\/reader\/zxing_reader\.wasm\?url/);
assert.match(adapter, /prepareZXingModule\([\s\S]*fireImmediately: true/);
assert.match(adapter, /resolveScannerRoiCrop\(options\.scanRegion, dimensions\.width, dimensions\.height\)/);
assert.match(adapter, /if \(!crop\) return \[\]/, 'invalid ROI must fail closed');
assert.match(adapter, /decodeTemporalSnapshot\(/);
assert.match(adapter, /measureScannerFocusQuality\(/);
assert.match(adapter, /createScannerTemporalSnapshot\(/);
assert.doesNotMatch(adapter, /getUserMedia|requestAnimationFrame|requestVideoFrameCallback|srcObject/);
assert.match(candidateFactory, /zxingWasmDecoderFactory/);
assert.match(candidateFactory, /await import\('\.\/zxingWasmDecoder'\)/);
assert.match(defaultFactory, /new ZXingDecoderAdapter\(\)/);
assert.doesNotMatch(defaultFactory, /zxingWasmDecoder|ZXingWasmDecoderAdapter/);
assert.doesNotMatch(session, /zxingWasmDecoder|ZXingWasmDecoderAdapter/);
console.log('ZXing-C++ WASM candidate adapter contract tests passed.');
